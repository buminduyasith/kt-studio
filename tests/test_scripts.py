class PluginFiles(unittest.TestCase):
    def frontmatter(self, skill_md: Path) -> dict:
        text = skill_md.read_text()
        m = re.match(r"---\n(.*?)\n---\n", text, re.S)
        self.assertIsNotNone(m, f"{skill_md} has no frontmatter")
        fields = {}
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            v = v.strip()
            fields[k.strip()] = json.loads(v) if v.startswith('"') else v
        return fields

    def test_skills(self):
        names = set()
        for skill_md in sorted((PLUGIN / "skills").glob("*/SKILL.md")):
            fm = self.frontmatter(skill_md)
            names.add(fm["name"])
            self.assertLessEqual(len(fm["description"]), 1024, skill_md)
            self.assertNotRegex(fm["description"], r"^(Turn|Make|Set|Check|Change)\b", "third person, please")
            self.assertLess(len(skill_md.read_text().splitlines()), 500, skill_md)
            self.assertIn("allowed-tools", fm, skill_md)
        self.assertEqual(names, {"make", "init", "update", "doctor"})

    def test_references_named_in_skill_exist(self):
        text = (SKILL / "SKILL.md").read_text()
        for ref in set(re.findall(r"references/[a-z-]+\.md", text)):
            self.assertTrue((SKILL / ref).is_file(), ref)

    def test_version_only_in_plugin_json(self):
        version = json.loads((PLUGIN / ".claude-plugin" / "plugin.json").read_text())["version"]
        self.assertRegex(version, r"^\d+\.\d+\.\d+$")
        market = json.loads((REPO / ".claude-plugin" / "marketplace.json").read_text())
        entry = market["plugins"][0]
        self.assertNotIn("version", entry, "keep the version only in plugin.json")
        self.assertTrue((REPO / entry["source"]).resolve() == PLUGIN.resolve())
        self.assertFalse((REPO / "CHANGELOG.md").exists(), "release notes go in the GitHub release")

    def test_no_secrets_in_samples(self):
        for f in (REPO / "samples").glob("*/.kt-studio/*"):
            if f.is_file():
                self.assertNotRegex(f.read_text(errors="ignore"), r"(?i)password\s*[:=]\s*\S{6,}", f)


