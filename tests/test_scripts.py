def run(*cmd, cwd=None, check=True):
    res = subprocess.run([str(c) for c in cmd], cwd=cwd, capture_output=True, text=True, env=GIT_ENV)
    if check and res.returncode:
        raise AssertionError(f"{cmd} failed ({res.returncode}):\n{res.stdout}\n{res.stderr}")
    return res


class Tmp(unittest.TestCase):
    def setUp(self):
        self.dir = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.dir, True)

    def write(self, rel: str, text: str) -> Path:
        p = self.dir / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        return p


class ProjectFolder(Tmp):
    def test_folder_layout_found_from_inside(self):
        self.write(".kt-studio/config.yml", "project: X\n")
        (self.dir / "src" / "deep").mkdir(parents=True)
        p = project.find(self.dir / "src" / "deep")
        self.assertEqual(p.layout, "folder")
        self.assertEqual(p.root, self.dir.resolve())
        self.assertEqual(p.instructions, self.dir.resolve() / ".kt-studio" / "instructions.md")
        self.assertEqual(p.out, self.dir.resolve() / ".kt-studio")

    def test_gitignore_keeps_only_the_settings_and_answers(self):
        self.write(".kt-studio/config.yml", "project: X\n")
        self.write(".kt-studio/instructions.md", "# x\n")
        self.write(".kt-studio/learned.yml", "audience:\n  - qa\n")
        self.write(".kt-studio/features/refunds/feature.yml", "feature: refunds\n")
        self.write(".kt-studio/features/refunds/runs/r1/5-videos/v.mp4", "x")
        self.write(".kt-studio/runtime/x.txt", "x")
        project.write_gitignore(self.dir / ".kt-studio")
        run("git", "init", "-q", cwd=self.dir)
        for path in (".kt-studio/runtime/x.txt", ".kt-studio/features/refunds/runs/r1/5-videos/v.mp4"):
            self.assertEqual(run("git", "check-ignore", path, cwd=self.dir, check=False).returncode, 0, path)
        kept = run("git", "check-ignore", ".kt-studio/config.yml", ".kt-studio/instructions.md", ".kt-studio/learned.yml",
                   ".kt-studio/features/refunds/feature.yml", cwd=self.dir, check=False)
        self.assertEqual(kept.stdout.strip(), "")

    def test_gitignore_upgrades_its_own_file_only(self):
        old = self.write(".kt-studio/.gitignore", "# Generated by KT Studio. Only your settings are committed: config.yml "
                                                  "and instructions.md.\n*\n!.gitignore\n!config.yml\n!instructions.md\n")
        project.write_gitignore(self.dir / ".kt-studio")
        self.assertIn("!features/*/feature.yml", old.read_text())
        own = "# mine\n*\n!.gitignore\n!config.yml\n!instructions.md\n"
        old.write_text(own)
        project.write_gitignore(self.dir / ".kt-studio")
        self.assertEqual(old.read_text(), own)

    def test_new_project_goes_next_to_claude_md(self):
        run("git", "init", "-q", cwd=self.dir)
        self.write("CLAUDE.md", "# p\n")
        (self.dir / "src" / "deep").mkdir(parents=True)
        p = project.find(self.dir / "src" / "deep")
        self.assertEqual(p.layout, "none")
        self.assertEqual(p.root, self.dir.resolve())
        self.write("services/api/.claude/settings.json", "{}")
        self.assertEqual(project.find(self.dir / "services" / "api").root, (self.dir / "services" / "api").resolve())

    def test_new_run_goes_in_the_feature_folder(self):
        out = self.dir / ".kt-studio"
        path = run("bash", SCRIPTS / "new_run.sh", out, "refunds").stdout.strip().splitlines()[-1]
        self.assertEqual(Path(path).parent, out / "features" / "refunds" / "runs")
        self.assertEqual(json.loads((Path(path) / "run.json").read_text())["choices"], {})
        again = run("bash", SCRIPTS / "new_run.sh", out, "refunds").stdout
        self.assertIn("reusing run", again)


class ServiceTables(Tmp):
    def test_update_creates_tables_and_adds_environments(self):
        p = self.dir / "i.md"
        services.update(p, [{"name": "Back office", "env": "dev", "url": "https://a.dev", "for": "Back office"}], "i.md")
        said = services.update(p, [{"name": "back office", "env": "qa", "url": "https://a.qa"},
                                   {"name": "Shop", "env": "dev", "url": "https://s.dev"}], "i.md")
        self.assertTrue(any("environment qa" in s for s in said))
        svc, envs, addr = services.read(p)
        self.assertEqual([s["name"] for s in svc], ["Back office", "Shop"])
        self.assertEqual(envs, ["dev", "qa"])
        self.assertEqual(addr["Back office"], {"dev": "https://a.dev", "qa": "https://a.qa"})
        self.assertEqual(addr["Shop"], {"dev": "https://s.dev"})

    def test_never_changes_what_the_person_wrote(self):
        p = self.dir / "i.md"
        services.update(p, [{"name": "Shop", "env": "qa", "url": "https://qa.one"}], "i.md")
        said = services.update(p, [{"name": "Shop", "env": "qa", "url": "https://qa.two"}], "i.md")
        self.assertTrue(any(s.startswith("kept:") for s in said))
        self.assertEqual(services.read(p)[2]["Shop"]["qa"], "https://qa.one")

    def test_names_match_without_a_note_in_brackets(self):
        self.assertTrue(services.same_service("Loans API (`api/`)", "loans api"))
        self.assertFalse(services.same_service("Loans API", "Loans worker"))

    def test_logging_in_table(self):
        p = self.write("i.md", """# x

## Logging in

| Service | Environment | How | The person runs | Session file |
| --- | --- | --- | --- | --- |
| Shop | local | none | | |
| Shop, Back office | dev, qa | script | `node login.mjs {env}` | .auth-team/{env}.json |
| * | all | window | | |
""")
        self.assertEqual(services.login_for(p, "Shop", "local")["how"], "none")
        self.assertEqual(services.login_for(p, "Back office", "qa")["how"], "script")
        self.assertEqual(services.login_for(p, "Back office", "qa")["run"], "node login.mjs {env}")
        self.assertEqual(services.login_for(p, "Reports", "staging")["how"], "window")


class Apps(Tmp):
    def setUp(self):
        super().setUp()
        self.write(".kt-studio/config.yml", "project: X\n")
        self.run_dir = self.dir / ".kt-studio" / "runs" / "r1"
        self.write(".kt-studio/runs/r1/run.json", '{"apps": []}')

    def apps(self, apps: list) -> tuple[str, list]:
        res = run("python3", SCRIPTS / "apps.py", self.dir, self.run_dir, json.dumps(apps))
        return res.stdout, json.loads((self.run_dir / "run.json").read_text())["apps"]

    def test_script_login_from_the_table(self):
        self.write(".kt-studio/instructions.md", """# x

## Logging in

| Service | Environment | How | The person runs | Session file |
| --- | --- | --- | --- | --- |
| Back office | qa | script | `node login.mjs {env}` | .auth-team/{env}.json |
""")
        out, apps = self.apps([{"name": "Back office", "env": "qa", "url": "http://127.0.0.1:9/admin"}])
        a = apps[0]
        self.assertEqual((a["key"], a["how"], a["run"], a["login"]), ("back-office-qa", "script", "node login.mjs qa", True))
        self.assertEqual(a["session"], str((self.dir / ".auth-team" / "qa.json").resolve()))
        self.assertIn("ask the person to run this themselves", out)
        self.assertIn("never run a login command yourself", out)

    def test_window_when_the_page_shows_a_login_and_no_row(self):
        out, apps = self.apps([{"name": "Shop", "env": "local", "url": "http://127.0.0.1:9", "login": True}])
        self.assertEqual(apps[0]["how"], "window")
        self.assertTrue(apps[0]["session"].endswith("/.kt-studio/runtime/.auth/kt-shop-local.json"))
        self.assertIn("login.sh open", out)

    def test_needs_an_environment(self):
        res = run("python3", SCRIPTS / "apps.py", self.dir, self.run_dir,
                  json.dumps([{"name": "Shop", "url": "http://127.0.0.1:9"}]), check=False)
        self.assertNotEqual(res.returncode, 0)
        self.assertIn("environment", res.stderr)


class Choices(Tmp):
    INSTRUCTIONS = """# I

## Addresses

| Service | local | dev | qa |
| --- | --- | --- | --- |
| Shop | http://localhost:3000 | https://shop.dev.acme.example | https://shop.qa.acme.example |
"""

    def setUp(self):
        super().setUp()
        self.write(".kt-studio/config.yml", "project: Acme\n")
        self.write(".kt-studio/instructions.md", self.INSTRUCTIONS)
        self.proj = project.find(self.dir)

    def ask(self, feature="refunds", **kw):
        return choices.ask(self.proj, feature, kw.pop("keys", choices.ROUND_ONE), kw.pop("given", {}), kw.pop("suggest", {}))

    def test_first_video_asks_with_the_default_first(self):
        res = self.ask()
        self.assertEqual([q["key"] for q in res["ask"]], ["audience", "show", "environment"])
        self.assertEqual(res["ask"][0]["options"][0]["label"], "Developer new to the area (Recommended)")
        self.assertTrue(all(2 <= len(q["options"]) <= 4 for q in res["ask"]))
        self.assertEqual(res["use"], {})

    def test_the_request_settles_and_labels_become_values(self):
        res = self.ask(given={"audience": "QA or tester", "show": "code"})
        self.assertEqual(res["use"]["audience"]["value"], "qa")
        self.assertEqual(res["ask"], [])  # code only: no environment question
        self.assertIn("you asked for it", res["say"])

    def test_the_instructions_default_environment(self):
        self.write(".kt-studio/instructions.md", self.INSTRUCTIONS + "\n## Before the run\n\n- When the request names no environment, use qa.\n")
        res = self.ask(given={"audience": "qa", "show": "screens"})
        self.assertEqual(res["use"]["environment"], {"value": "qa", "label": "qa", "from": "instructions"})

    def test_no_app_means_code_only(self):
        self.write(".kt-studio/instructions.md", "# I\n")
        res = self.ask(given={"audience": "qa"})
        self.assertEqual(res["use"]["show"]["from"], "no app")
        self.assertEqual(res["ask"], [])

    def test_record_saves_the_feature_and_the_run(self):
        out = self.dir / ".kt-studio"
        r = Path(run("bash", SCRIPTS / "new_run.sh", out, "refunds").stdout.strip().splitlines()[-1])
        choices.record(self.proj, "refunds", {"audience": "QA or tester (Recommended)", "show": "screens", "environment": "qa"},
                       ["audience", "show", "environment"], ["Flows: full refund: part refund"], r, "Order refunds")
        saved = choices.read_yml(out / "features" / "refunds" / "feature.yml")
        self.assertEqual((saved["audience"], saved["title"], saved["runs"]), ("qa", "Order refunds", [r.name]))
        self.assertEqual(saved["notes"], ["Flows: full refund: part refund"])
        self.assertEqual(json.loads((r / "run.json").read_text())["choices"]["audience"], "qa")
        res = self.ask()
        self.assertEqual({k: u["from"] for k, u in res["use"].items()}, {"audience": "feature", "show": "feature"})
        self.assertEqual(res["ask"][0]["key"], "environment")  # never settled by an earlier video
        self.assertEqual(res["ask"][0]["options"][0]["label"], "qa (Recommended)")

    def test_three_same_answers_stop_the_question(self):
        for n in range(3):
            res = self.ask(f"f{n}")
            self.assertIn("audience", [q["key"] for q in res["ask"]])
            choices.record(self.proj, f"f{n}", {"audience": "support", "environment": "dev", "depth": "overview"},
                           ["audience", "environment", "depth"], [], None, "")
            if n == 0:
                self.assertEqual(self.ask("next")["ask"][0]["options"][0]["value"], "support")
        res = self.ask("next", keys=["audience", "show", "environment", "depth"])
        self.assertEqual(res["use"]["audience"]["from"], "learned")
        self.assertEqual([q["key"] for q in res["ask"]], ["show", "environment", "depth"])

    def test_only_learn_keys_count(self):
        choices.record(self.proj, "a", {"audience": "qa", "show": "code"}, ["audience"], [], None, "")
        learned = choices.read_yml(self.proj.learned)
        self.assertEqual(learned, {"audience": ["qa"]})

    def test_cli_refuses_a_bad_feature_name(self):
        res = run("python3", SCRIPTS / "choices.py", "ask", self.dir, "Bad Name", check=False)
        self.assertNotEqual(res.returncode, 0)
        self.assertIn("lowercase letters", res.stderr)


