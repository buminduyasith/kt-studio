        team = self.dir / ".auth-team"
        team.mkdir()
        (team / "dev.json").write_text("{}")
        rt = self.dir / ".kt-studio" / "runtime"
        rt.mkdir(parents=True)
        os.symlink("../../.auth-team", rt / ".auth")
