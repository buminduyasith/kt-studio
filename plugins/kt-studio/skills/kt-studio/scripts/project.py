#!/usr/bin/env python3
"""Finds a project's KT Studio folder and settings. Every script uses this, so they all agree.

A project keeps its settings in one folder at its root, next to .claude/ and CLAUDE.md:

    <root>/.kt-studio/
        config.yml          settings (commit it)
        instructions.md     the project's own rules, its services and their addresses (commit it)
        learned.yml         the answers people picked, so later videos ask less (commit it; choices.py writes it)
        .gitignore          keeps everything else out of git
        runtime/            the recorder (not committed)
        features/<feature>/
            feature.yml     this feature's answers (commit it; choices.py writes it)
            runs/<run-id>/  one folder per video: research, storyboard, scripts, checks, videos (not committed)

<root> is the folder that holds .kt-studio/. Every path in config.yml is relative to <root>. In a new
project it is the folder the skill names (Claude Code's project folder), else the nearest folder at or
above the current one that holds .claude/ or CLAUDE.md, inside the same git repo.

Usage: python3 project.py [folder] [--shell]
  Prints the root, the layout, the config, the instructions, the output folder and the features
  folder. With --shell, as
  KT_ROOT=... lines for `eval` in bash. The folder (default: the current one) may be the root or any
  folder inside it.
       python3 project.py --gitignore <output-dir>
  Writes the output folder's .gitignore: nothing in it is committed except config.yml,
  instructions.md, learned.yml and each feature's feature.yml.
"""
from __future__ import annotations

import re
import shlex
import sys
from pathlib import Path

FOLDER = ".kt-studio"
GITIGNORE = """# Generated by KT Studio. Only your settings are committed: config.yml, instructions.md,
# learned.yml and each feature's feature.yml. The recorder and the videos stay on this computer.
*
!.gitignore
!config.yml
!instructions.md
!learned.yml
!features/
!features/*/
!features/*/feature.yml
"""
GENERATED = "# Generated by KT Studio."


class Project:
    def __init__(self, root: Path, layout: str):
        self.root = root
        self.layout = layout  # "folder" (.kt-studio/config.yml exists) or "none" (not set up yet)

    @property
    def config(self) -> Path:
        return self.root / FOLDER / "config.yml"

    def setting(self, key: str) -> str:
        """A top-level "key: value" of the config, without comment and quotes. No YAML library needed."""
        text = self.config.read_text(errors="ignore") if self.config.is_file() else ""
        m = re.search(rf"^{re.escape(key)}:[ \t]*(.*)$", text, re.M)
        value = re.sub(r"\s+#.*$", "", m.group(1)).strip().strip("'\"") if m else ""
        return value

    @property
    def instructions(self) -> Path:
        value = self.setting("instructions")
        if value:
            return self.root / value
        return self.root / FOLDER / "instructions.md"

    @property
    def out(self) -> Path:
        value = self.setting("output_dir")
        if value:
            return self.root / value
        return self.root / FOLDER

    @property
    def features(self) -> Path:
        return self.out / "features"

    def feature(self, slug: str) -> Path:
        return self.features / slug

    @property
    def learned(self) -> Path:
        return self.out / "learned.yml"

    def rel(self, path: Path) -> str:
        try:
            return path.resolve().relative_to(self.root.resolve()).as_posix()
        except ValueError:
            return str(path)


def find(start: str | Path = ".") -> Project:
    """The project whose settings are in `start` or the nearest folder above it."""
    start = Path(start).resolve()
    if start.name == FOLDER:
        start = start.parent
    for folder in [start, *start.parents]:
        if (folder / FOLDER / "config.yml").is_file():
            return Project(folder, "folder")
    return Project(new_root(start), "none")


def new_root(start: Path) -> Path:
    """Where a new project's .kt-studio/ goes: the nearest folder at or above `start` that holds .claude/
    or CLAUDE.md (where Claude Code keeps the project's own files), without leaving the git repo and
    never the home folder (it has a .claude/ of its own). None found: the git repo's top, else `start`."""
    home = Path.home().resolve()
    for folder in [start, *start.parents]:
        if folder == home:
            break
        if (folder / ".claude").is_dir() or (folder / "CLAUDE.md").is_file():
            return folder
        if (folder / ".git").exists():
            return folder
    return start


def write_gitignore(out: Path) -> None:
    """The output folder's .gitignore: everything stays out of git except the two settings files."""
    out.mkdir(parents=True, exist_ok=True)
    ignore = out / ".gitignore"
    text = ignore.read_text(errors="ignore") if ignore.is_file() else ""
    # A file KT Studio wrote before (or none) gets the current rules; one the person wrote is left alone.
    if text != GITIGNORE and (not text or text.startswith(GENERATED) or "!config.yml" not in text):
        ignore.write_text(GITIGNORE)


def main() -> None:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--gitignore" in sys.argv:
        write_gitignore(Path(args[0]))
        return
    p = find(args[0] if args else ".")
    values = {
        "KT_ROOT": str(p.root),
        "KT_LAYOUT": p.layout,
        "KT_CONFIG": str(p.config),
        "KT_INSTRUCTIONS": str(p.instructions),
        "KT_OUT": str(p.out),
        "KT_FEATURES": str(p.features),
    }
    if "--shell" in sys.argv:
        for k, v in values.items():
            print(f"{k}={shlex.quote(v)}")
    else:
        for k, v in values.items():
            print(f"{k[3:].lower():13} {v}")


if __name__ == "__main__":
    main()
